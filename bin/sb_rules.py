#!/usr/bin/env python3
"""L3 규칙층 생성기 — type:feedback 자동 메모리를 scope 별 rules/<scope>.md 로 모은다.

정본은 각 프로젝트의 feedback 메모리 파일(Claude Code 프로젝트 폴더/<slug>/memory/*.md)이다. 여기서 만드는
파일은 생성물이라 손으로 고치지 않는다 — 첫 줄 표식(MARKER)이 있는 파일만 덮어쓰거나 지우고, 사람이 쓴 파일은
그대로 둔다. LLM 없이 본문을 그대로 옮기고 항목마다 출처 경로를 붙인다. scope 는 폴더 슬러그를 추측하지 않고,
그 프로젝트 세션 기록(jsonl)에 남은 실제 cwd 를 sb_scope 로 해석한다. 세션 기록이 정리돼 cwd 가 없으면 전에 그
폴더 규칙을 담았던 생성물의 scope 를 이어 쓴다(그것도 없으면 건너뛴다). 출력 폴더는 `sb search --mode rules` 가
읽는 곳(SB_RULES_DIR, 기본 $SB_HOME/rules)이다.

사용: sb rules [--dry-run] [--json] [--root <Claude Code 프로젝트 폴더>]
"""
import argparse
import json
import os
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sb_config  # noqa: E402
import sb_scope  # noqa: E402
from sync_automemory import (excluded_projects, parse_memory_file,  # noqa: E402
                             project_from_slug, projects_root, temp_roots)

MARKER = '<!-- generated by sb_rules.py from type:feedback auto-memory; do not edit, edit the source memory -->'
MAX_BYTES = 19000   # sb search --mode rules 는 앞 20000바이트만 읽는다 — 생략 안내 줄 몫을 남긴다
MAX_BODY = 800      # 규칙 하나가 한도를 독차지하지 않게. 나머지는 출처 파일에서 읽는다
SESSION_FILES = 5   # cwd 를 찾을 때 볼 최근 세션 기록 수
SESSION_LINES = 50  # 기록마다 앞에서 볼 줄 수(cwd 는 첫 몇 줄에 있다)
HEADING = '# 규칙 — '   # 생성물 둘째 줄. 뒤가 scope_id
SOURCE = '출처: '       # 규칙마다 붙는 정본 메모리 파일 경로


def rules_dir() -> Path:
    # sb_search._rules_items 가 읽는 곳과 같아야 한다.
    return Path(os.environ.get('SB_RULES_DIR') or sb_config.sb_path('rules')).expanduser()


def scope_file(scope_id: str) -> str:
    # sb_search._rules_items 와 같은 이름 규칙 — 한쪽을 바꾸면 다른 쪽도 바꾼다.
    return scope_id.replace('/', '__').replace('\\', '__').replace('..', '_') + '.md'


def _mtime(path: Path) -> float:
    try:
        return path.stat().st_mtime
    except OSError:
        return 0.0


def session_cwd(project_dir: Path) -> Optional[str]:
    """가장 최근 세션 기록들에서 cwd 를 읽는다. 없으면 None."""
    for record in sorted(project_dir.glob('*.jsonl'), key=_mtime, reverse=True)[:SESSION_FILES]:
        try:
            with record.open(encoding='utf-8', errors='replace') as stream:
                for _, line in zip(range(SESSION_LINES), stream):
                    try:
                        value = json.loads(line)
                    except ValueError:
                        continue
                    cwd = value.get('cwd') if isinstance(value, dict) else None
                    if isinstance(cwd, str) and cwd:
                        return cwd
        except OSError:
            continue
    return None


def _is_temp(cwd: str) -> bool:
    """임시 폴더에서 연 세션(테스트·일회성 실행)은 규칙 scope 로 남기지 않는다.
    뿌리 목록은 자동 메모리 가져오기(sync_automemory)와 같은 것을 쓴다. macOS 는 /tmp·/var/folders 의 실체가
    /private 아래라 realpath 로 비교한다."""
    real = os.path.normcase(os.path.realpath(cwd))
    return any(sb_scope.path_within(real, os.path.normcase(os.path.realpath(root))) for root in temp_roots())


def previous_scopes() -> Dict[str, str]:
    """기존 생성물에서 {memory 폴더: scope}. Claude Code 가 오래된 대화 기록(jsonl)을 정리하면 그 프로젝트는 cwd 를
    못 찾는다 — 그때 규칙층이 통째로 지워지지 않게 전에 그 폴더 규칙을 담았던 파일('출처:' 줄)의 scope 를 이어 쓴다."""
    found: Dict[str, str] = {}
    target = rules_dir()
    if not target.is_dir():
        return found
    for path in sorted(target.glob('*.md')):
        if not _is_generated(path):
            continue
        try:
            lines = path.read_text(encoding='utf-8').splitlines()
        except (OSError, UnicodeError):
            continue
        if len(lines) < 2 or not lines[1].startswith(HEADING):
            continue
        for line in lines:
            if line.startswith(SOURCE):
                found.setdefault(os.path.dirname(line[len(SOURCE):]), lines[1][len(HEADING):])
    return found


def collect(root: Optional[str] = None) -> Tuple[Dict[str, List[Dict[str, Any]]], List[Dict[str, str]]]:
    """→ ({scope_id: [규칙...]}, [건너뛴 프로젝트 폴더와 이유])."""
    base = projects_root(root)
    skip_projects = excluded_projects()   # 자동 메모리 가져오기에서 뺀 프로젝트는 규칙층에도 올리지 않는다
    previous = previous_scopes()
    groups: Dict[str, List[Dict[str, Any]]] = {}
    skipped: List[Dict[str, str]] = []
    for memory_dir in sorted(base.glob('*/memory')):
        if not memory_dir.is_dir() or project_from_slug(memory_dir.parent.name) in skip_projects:
            continue
        feedback = []
        for path in sorted(memory_dir.glob('*.md')):
            if path.name == 'MEMORY.md' or not path.is_file():
                continue
            try:
                memory = parse_memory_file(str(path))
            except (OSError, UnicodeError):
                continue
            if memory['type'] == 'feedback':
                feedback.append((path, memory))
        if not feedback:
            continue
        cwd = session_cwd(memory_dir.parent)
        if cwd and _is_temp(cwd):
            skipped.append({'dir': memory_dir.parent.name, 'reason': 'temp_cwd'})
            continue
        scope_id = sb_scope.resolve_scope_id(cwd)[0] if cwd else previous.get(str(memory_dir))
        if not scope_id:   # 세션 기록도, 전에 만든 rules 파일도 없다 — scope 를 추측하지 않는다
            skipped.append({'dir': memory_dir.parent.name, 'reason': 'no_cwd'})
            continue
        for path, memory in feedback:
            groups.setdefault(scope_id, []).append({
                'path': str(path), 'mtime': _mtime(path), 'title': memory['title'],
                'name': memory['name'], 'body': memory['body'].strip()})
    return groups, skipped


def render(scope_id: str, rules: List[Dict[str, Any]]) -> str:
    rules = sorted(rules, key=lambda r: (-r['mtime'], r['path']))   # 최신 규칙이 읽기 한도 안에 먼저 들어간다
    head = [MARKER, HEADING + scope_id, '',
            '사용자가 교정하거나 확인한 일하는 방식(type:feedback 메모리 {}건). 최신순.'.format(len(rules)), '']
    out, size, omitted = list(head), len('\n'.join(head).encode('utf-8')), 0
    for rule in rules:
        body = rule['body'] if len(rule['body']) <= MAX_BODY else rule['body'][:MAX_BODY] + ' …(이하 출처 참조)'
        block = '## {}\n{}\n\n{}{}\n'.format(rule['title'], body, SOURCE, rule['path'])
        cost = len(block.encode('utf-8')) + 1
        if size + cost > MAX_BYTES:
            omitted += 1
            continue
        out.append(block)
        size += cost
    if omitted:
        out.append('(용량 한도로 {}건 생략 — 출처 메모리 폴더 참조)'.format(omitted))
    return '\n'.join(out) + '\n'


def _is_generated(path: Path) -> bool:
    marker = MARKER.encode('utf-8')
    try:
        with path.open('rb') as stream:
            return stream.read(len(marker)) == marker
    except OSError:
        return False


def _atomic_write(path: Path, data: bytes) -> None:
    fd, temporary = tempfile.mkstemp(dir=str(path.parent), prefix='.' + path.name, suffix='.tmp')
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
        os.replace(temporary, str(path))
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def write(groups: Dict[str, List[Dict[str, Any]]], dry_run: bool = False) -> Dict[str, Any]:
    target = rules_dir()
    base = target.resolve()
    report: Dict[str, Any] = {'rules': sum(len(r) for r in groups.values()), 'written': [], 'unchanged': [],
                              'removed': [], 'kept': [], 'skipped': []}
    plan: Dict[Path, Tuple[str, List[Dict[str, Any]]]] = {}
    for scope_id, rules in sorted(groups.items()):
        path = (target / scope_file(scope_id)).resolve()
        if path.parent != base:
            # Windows 드라이브 문자(C:)가 남은 realpath scope 등은 rules 폴더 밖을 가리킨다 — sb search 도 못 읽는다.
            report['skipped'].append({'scope': scope_id, 'reason': 'unsafe_name'})
            continue
        plan[path] = (scope_id, rules)
    if plan and not dry_run:
        target.mkdir(parents=True, exist_ok=True)
    for path, (scope_id, rules) in plan.items():
        data = render(scope_id, rules).encode('utf-8')
        if path.is_file():
            if path.read_bytes() == data:
                report['unchanged'].append(path.name)
                continue
            if not _is_generated(path):
                report['kept'].append(path.name)   # 사람이 쓴 파일은 건드리지 않는다
                continue
        report['written'].append(path.name)
        if not dry_run:
            _atomic_write(path, data)
    if target.is_dir():
        for path in sorted(target.glob('*.md')):
            if path.resolve() not in plan and _is_generated(path):
                report['removed'].append(path.name)
                if not dry_run:
                    path.unlink()
    return report


def run(root: Optional[str] = None, dry_run: bool = False) -> Dict[str, Any]:
    if not projects_root(root).is_dir():
        # 원천 폴더가 안 보이면(설치 직후·경로 오류) 기존 생성물을 지우지 않고 아무것도 하지 않는다.
        return {'status': 'no_source', 'rules': 0, 'written': [], 'unchanged': [], 'removed': [],
                'kept': [], 'skipped': []}
    groups, skipped = collect(root)
    report = write(groups, dry_run=dry_run)
    report['skipped'] = skipped + report['skipped']
    return {'status': 'ok', **report}


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--dry-run', action='store_true', help='쓰거나 지울 파일만 보고하고 바꾸지 않는다')
    parser.add_argument('--json', action='store_true')
    parser.add_argument('--root', help='Claude Code 프로젝트 폴더 (기본 ~/.claude/projects)')
    args = parser.parse_args(argv)
    try:
        report = run(args.root, dry_run=args.dry_run)
    except OSError as exc:
        if args.json:
            print(json.dumps({'status': 'error', 'error': str(exc)}, ensure_ascii=False))
        else:
            print('sb_rules: {}'.format(exc), file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(report, ensure_ascii=False))
    else:
        print('status={} rules={} written={} unchanged={} removed={} kept={} skipped={}'.format(
            report['status'], report['rules'], len(report['written']), len(report['unchanged']),
            len(report['removed']), len(report['kept']), len(report['skipped'])))
    return 0


if __name__ == '__main__':
    sys.exit(main())
